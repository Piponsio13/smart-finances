-- Apply before deploying the API with ddl-auto=validate. Development uses ddl-auto=update.
BEGIN;
CREATE TABLE IF NOT EXISTS social_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(16) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (provider, subject)
);
CREATE TABLE IF NOT EXISTS used_social_tokens (
    digest VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS used_social_tokens_expiry_idx ON used_social_tokens (expires_at);
COMMIT;
